/*Proteger o estado é impedir que qualquer um altere as variáveis de um objeto de forma
diretaa ou inválida. Mantendo o controle de mudanças apenas dentro da classe. Um exemplo é 
a máquina de café que voçê não coloca água conforme a sua vontade e sim conforme o tamanho
escolhido no display.

Esconder a implementação é esconder os detalhes de ccomo a tarefa é executada por dentro
quem usa apenas aperta botões sem precisar saber como o código está trabalhando.
Usando a máquina de café como exempo, voçê escolhe seu café pelos botões da máquina sem 
saber como a máquina moe seu café ou mede a quantidade de água.

Encapsular as regras de negócio é basicamente colocar validações do sistema dentro da classe
para garantir que o processo siga as regras corretas antes de executar uma ação. Ainda 
usando a m´aquina de café como exemplo, se voçê escolher um café e a máquina estiver sem
aágua ou sem grãos o processo não é feito. A regra de negócio certifica de que tudo
que é necessário para a ação esteja á disposiçao.